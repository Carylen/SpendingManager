import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const source = new URL('../design/tokens.json', import.meta.url);
const target = new URL('../src/styles/tokens.css', import.meta.url);

const tokens = JSON.parse(await readFile(source, 'utf8'));
const [light, dark] = tokens.color.themes.map((theme) => theme.id);

const resolve = (value) => value.replace(/^\{(.+)\}$/, 'var(--$1)');
const valueFor = (token, theme) =>
  resolve(
    typeof token.value === 'string' ? token.value : (token.value[theme] ?? token.value[light]),
  );
const declarations = (list, theme) =>
  list.map((token) => `  --${token.name}: ${valueFor(token, theme)};`).join('\n');

const themed = [...tokens.color.tokens, ...tokens.shadow.tokens];
const fixed = [...tokens.spacing.tokens, ...tokens.radius.tokens];
const darkOnly = themed.filter((token) => typeof token.value !== 'string' && token.value[dark]);

const css = `/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit. */
:root {
${declarations(themed, light)}
${declarations(fixed, light)}
  --font-sans: 'Plus Jakarta Sans Variable', ui-sans-serif, system-ui, sans-serif;
  --font-mono: 'DM Mono', ui-monospace, SFMono-Regular, monospace;
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${declarations(darkOnly, dark).replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}

:root[data-theme='dark'] {
${declarations(darkOnly, dark)}
  color-scheme: dark;
}
`;

const targetPath = fileURLToPath(target);
const options = await resolveConfig(targetPath);
await writeFile(target, await format(css, { ...options, filepath: targetPath }));
